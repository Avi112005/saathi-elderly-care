#!/usr/bin/env node
/**
 * Runs the Prisma CLI against the right database provider.
 *
 *   node scripts/prisma.mjs generate
 *   node scripts/prisma.mjs db push
 *
 * `prisma/schema.prisma` (SQLite) is the single source of truth. When DATABASE_URL is a
 * PostgreSQL URL — e.g. Supabase in production — an equivalent PostgreSQL schema is
 * derived into `prisma/postgres/schema.prisma` and used instead. Local development and
 * the test suite keep using a zero-setup SQLite file.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const baseSchema = path.join(root, "prisma", "schema.prisma");
const pgSchema = path.join(root, "prisma", "postgres", "schema.prisma");

// Prisma reads .env itself, but this script needs DATABASE_URL to pick the provider.
// Variables already set (Vercel, CI, --env-file) always win over the file.
if (!process.env.DATABASE_URL && existsSync(path.join(root, ".env")) && typeof process.loadEnvFile === "function") {
  process.loadEnvFile(path.join(root, ".env"));
}

export function isPostgresUrl(url = "") {
  return /^postgres(ql)?:\/\//i.test(url);
}

/** Rewrites the SQLite datasource block into a PostgreSQL one (pooled + direct URLs). */
export function toPostgresSchema(source) {
  const datasource = /datasource db \{[^}]*\}/;
  if (!datasource.test(source)) throw new Error("Could not find the `datasource db` block in prisma/schema.prisma");
  const header = "// GENERATED by scripts/prisma.mjs from prisma/schema.prisma — do not edit by hand.\n";
  return (
    header +
    source.replace(
      datasource,
      `datasource db {
  provider  = "postgresql"
  // Pooled connection (Supabase transaction pooler, port 6543) used by the running app.
  url       = env("DATABASE_URL")
  // Direct/session connection (port 5432) used by \`prisma db push\`.
  directUrl = env("DIRECT_URL")
}`,
    )
  );
}

function main() {
  const args = process.argv.slice(2);
  if (args.length === 0) {
    console.error("Usage: node scripts/prisma.mjs <prisma command…>");
    process.exit(1);
  }
  const postgres = isPostgresUrl(process.env.DATABASE_URL);
  let schema = baseSchema;
  if (postgres) {
    mkdirSync(path.dirname(pgSchema), { recursive: true });
    writeFileSync(pgSchema, toPostgresSchema(readFileSync(baseSchema, "utf8")));
    schema = pgSchema;
    // `directUrl` must resolve even when only one URL was provided.
    process.env.DIRECT_URL ||= process.env.DATABASE_URL;
  }
  console.info(`[prisma] ${postgres ? "PostgreSQL" : "SQLite"} → prisma ${args.join(" ")}`);
  const bin = path.join(root, "node_modules", "prisma", "build", "index.js");
  execFileSync(process.execPath, [bin, ...args, "--schema", schema], { stdio: "inherit", env: process.env, cwd: root });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main();
